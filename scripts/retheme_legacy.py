#!/usr/bin/env python3
"""Bring the three hand-written membrane pages onto the site shell.

These were generated by older scripts with their own dark palette and their own
nav. Rather than regenerate them (the inspector is a working three.js app), the
site header is injected and their local palette is re-pointed at the site
tokens, so they inherit light/dark and the shared navigation.

Idempotent: re-running detects the marker and does nothing.

    python scripts/retheme_legacy.py
"""
from __future__ import annotations

import re, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import site_shell as sh

ROOT = Path(__file__).resolve().parent.parent
MEM = ROOT / "docs" / "membranes"
MARK = "<!--rethemed-->"

# the app pages keep a dark interior (a 3D canvas wants one) but take their
# colours from the site tokens so the two never drift apart
