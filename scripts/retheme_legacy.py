def strip_local_palette(html: str) -> str:
    """Neutralise the old :root block so the site tokens win."""
    return re.sub(r":root\{--bg:#0f1420;[^}]*\}", "", html, count=1)


def inject(path: Path, active: str, doc_page: bool) -> bool:
    html = path.read_text()
    if MARK in html:
        print(f"  already themed: {path.name}")
        return False
    header = sh.nav(active, 1)
    css = DOC_STYLE if doc_page else ""
    base = ('<link rel="stylesheet" href="../assets/app.css">'
            '<script src="../assets/site.js"></script>')
    inject_head = ('<meta name="viewport" content="width=device-width,initial-scale=1">'
                   + (base + css if doc_page else APP_TOKENS) + MARK)

    if doc_page:
        html = strip_local_palette(html)

    # head injection: after </title> if present, else at the very top
    if "</title>" in html:
        html = html.replace("</title>", "</title>" + inject_head, 1)
    else:
        html = inject_head + html

    # body injection: right after <body...> if present, else before the first
    # structural element the page uses
    m = re.search(r"<body[^>]*>", html)
    if m:
        html = html[:m.end()] + header + html[m.end():]
    else:
        for anchor in ('<div id=app>', '<nav class=bar>', '<nav class="bar">',
                       '<div class=container>', '<div class="container">', '<h1'):
            if anchor in html:
                html = html.replace(anchor, header + anchor, 1)
                break
        else:
            html = header + html
    path.write_text(html)
    print(f"  themed: {path.name}")
    return True


def fix_inspector_height():
    """The app assumed the full viewport; it now sits under a 52px header."""
    p = MEM / "inspector.html"
    h = p.read_text()
    if "calc(100vh - 52px)" in h:
        return
    h = h.replace("#app{display:flex;height:100vh}",
                  "#app{display:flex;height:calc(100vh - 52px)}")
    p.write_text(h)
    print("  inspector: canvas height adjusted for the header")


def main():
    inject(MEM / "inspector.html", "membranes/inspector.html", doc_page=False)
    fix_inspector_height()
    inject(MEM / "methods.html", "membranes/inspector.html", doc_page=True)
    inject(MEM / "index.html", "membranes/views.html", doc_page=True)


if __name__ == "__main__":
    main()
